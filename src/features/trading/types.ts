/**
 * TradePulse - Trading Domain Types & Interfaces
 */

export type OrderSide = 'buy' | 'sell';
export type OrderType = 'market' | 'limit';
export type OrderStatus = 'pending' | 'filled' | 'canceled' | 'rejected';

export interface TradeOrder {
  id: string;
  symbol: string;             // e.g. 'BTCUSDT'
  baseAsset: string;          // e.g. 'BTC'
  quoteAsset: string;         // e.g. 'USDT'
  side: OrderSide;
  type: OrderType;
  price: number;              // Limit price for limit orders, executable quote for market
  quantity: number;           // Asset quantity
  filledPrice?: number;
  filledQuantity?: number;
  fee: number;                // Simulated fee in USDT
  status: OrderStatus;
  reservedAmount: number;     // USDT reserved for buy, or asset quantity reserved for sell
  createdAt: number;
  filledAt?: number;
  rejectionReason?: string;
  protectiveOrderId?: string; // Optional link if generated by SL/TP trigger
  orderLabel?: string;        // Optional display tag e.g. 'Stop-Loss' | 'Take-Profit'
}

export type TriggerType = 'stop-loss' | 'take-profit';
export type ProtectiveOrderStatus = 'active' | 'triggered' | 'executed' | 'cancelled' | 'failed';

export interface ProtectiveOrder {
  id: string;
  symbol: string;
  baseAsset: string;
  quoteAsset: string;
  side: 'sell';
  triggerType: TriggerType;
  triggerPrice: number;
  quantity: number;
  status: ProtectiveOrderStatus;
  groupId: string;            // Shared between linked SL and TP OCO pair
  createdAt: number;
  triggeredAt?: number;
  executedAt?: number;
  executionPrice?: number;
  fee?: number;
  realizedPnl?: number;
  executionOrderId?: string;
  error?: string;
}

export interface TradeExecution {
  id: string;
  orderId: string;
  symbol: string;
  baseAsset: string;
  quoteAsset: string;
  side: OrderSide;
  type: OrderType;
  price: number;
  quantity: number;
  grossValue: number;         // price * quantity
  fee: number;                // fee in USDT
  netValue: number;           // grossValue + fee for buy, grossValue - fee for sell
  realizedPnl?: number;       // calculated for sell executions
  timestamp: number;
}

export interface Position {
  symbol: string;
  baseAsset: string;
  quoteAsset: string;
  quantity: number;           // Total held
  reservedQuantity: number;   // Locked in open limit sell orders
  availableQuantity: number;  // quantity - reservedQuantity
  averageEntryPrice: number;  // Cost basis per unit, including buy-side fees
  totalCostBasis: number;     // Total acquisition cost including fees
  realizedPnl: number;        // Cumulative realized profit/loss
  openedAt: number;
  updatedAt: number;
}

export interface LiveQuote {
  symbol: string;
  bidPrice: number;
  askPrice: number;
  lastPrice: number;
  timestamp: number;
}

export interface PortfolioStats {
  totalEquity: number;
  availableUsdt: number;
  reservedUsdt: number;
  totalUsdt: number;
  investedValue: number;
  unrealizedPnl: number;
  unrealizedPnlPercent: number;
  realizedPnl: number;
  totalFeesPaid: number;
  totalReturnPercent: number;
}

export interface EquitySnapshot {
  id: string;
  timestamp: number;
  totalEquity: number;
  availableUsdt: number;
  investedValue: number;
  unrealizedPnl: number;
  realizedPnl: number;
}

export interface TradeNotification {
  id: string;
  type: 'success' | 'error' | 'info' | 'warning';
  title: string;
  message: string;
  timestamp: number;
}
